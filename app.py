# SECTION 2: TAX EVALUATION
# =====================================================

st.header("Tax Evaluation")

civil_servants = get_all_civil_servants()

if civil_servants:

    employee_options = {}

    for employee in civil_servants:
        label = f"{employee[1]} - {employee[2]}"
        employee_options[label] = employee

    selected_employee_label = st.selectbox(
        "Select Civil Servant",
        list(employee_options.keys()),
        key="tax_employee_selection"
    )

    selected_employee = employee_options[selected_employee_label]

    (
        database_id,
        selected_employee_id,
        selected_name,
        selected_gender,
        selected_department,
        selected_position,
        monthly_basic,
        monthly_housing,
        monthly_transport,
        monthly_other
    ) = selected_employee

    st.subheader("Employee Details")

    col1, col2 = st.columns(2)

    with col1:
        st.write(f"**Employee ID:** {selected_employee_id}")
        st.write(f"**Full Name:** {selected_name}")
        st.write(f"**Gender:** {selected_gender}")

    with col2:
        st.write(f"**Department:** {selected_department}")
        st.write(f"**Position:** {selected_position}")

    annual_basic = float(monthly_basic) * 12
    annual_housing = float(monthly_housing) * 12
    annual_transport = float(monthly_transport) * 12
    annual_other = float(monthly_other) * 12

    gross_income = (
        annual_basic
        + annual_housing
        + annual_transport
        + annual_other
    )

    st.subheader("Annual Income")

    col1, col2 = st.columns(2)

    with col1:
        st.metric("Annual Basic Salary", format_money(annual_basic))
        st.metric("Annual Housing Allowance", format_money(annual_housing))

    with col2:
        st.metric("Annual Transport Allowance", format_money(annual_transport))
        st.metric("Annual Other Allowances", format_money(annual_other))

    st.metric("Total Annual Gross Income", format_money(gross_income))

    st.subheader("Annual Deductions and Reliefs")

    col1, col2 = st.columns(2)

    with col1:
        pension = st.number_input(
            "Annual Pension Contribution (NGN)",
            min_value=0.0,
            value=0.0,
            step=10000.0,
            key="annual_pension"
        )

        nhf = st.number_input(
            "Annual NHF Contribution (NGN)",
            min_value=0.0,
            value=0.0,
            step=5000.0,
            key="annual_nhf"
        )

        nhis = st.number_input(
            "Annual NHIS Contribution (NGN)",
            min_value=0.0,
            value=0.0,
            step=5000.0,
            key="annual_nhis"
        )

    with col2:
        life_insurance = st.number_input(
            "Annual Life Insurance Premium (NGN)",
            min_value=0.0,
            value=0.0,
            step=5000.0,
            key="annual_life_insurance"
        )

        annual_rent = st.number_input(
            "Annual Rent Paid (NGN)",
            min_value=0.0,
            value=0.0,
            step=50000.0,
            key="annual_rent"
        )

    rent_relief = min(annual_rent * 0.20, 500000.0)

    total_deductions = (
        pension
        + nhf
        + nhis
        + life_insurance
        + rent_relief
    )

    taxable_income = max(0.0, gross_income - total_deductions)

    col1, col2 = st.columns(2)

    with col1:
        st.metric("Rent Relief", format_money(rent_relief))
        st.metric("Total Deductions/Reliefs", format_money(total_deductions))

    with col2:
        st.metric("Gross Annual Income", format_money(gross_income))
        st.metric("Taxable Income", format_money(taxable_income))

    st.info(
        "Confirm that the deductions and reliefs entered are eligible "
        "under the applicable tax rules before official use."
    )
    current_input_signature = (
        selected_employee_id,
        float(gross_income),
        float(total_deductions),
        float(taxable_income)
    )
    current_input_signature = (
        selected_employee_id,
        float(gross_income),
        float(total_deductions),
        float(taxable_income)
    )

    if st.button("Calculate Tax", use_container_width=True, type="primary"):
        annual_tax = calculate_tax(taxable_income)
        monthly_paye = annual_tax / 12

        st.session_state["tax_result"] = {
            "employee_id": selected_employee_id,
            "employee_name": selected_name,
            "evaluation_date": date.today().isoformat(),
            "gross_income": gross_income,
            "deductions": total_deductions,
            "taxable_income": taxable_income,
            "annual_tax": annual_tax,
            "monthly_paye": monthly_paye,
            "input_signature": current_input_signature
        }

    tax_result = st.session_state.get("tax_result")

    if tax_result and tax_result["employee_id"] == selected_employee_id:

        st.subheader("Current Tax Result")

        col1, col2 = st.columns(2)

        with col1:
            st.metric(
                "Annual Tax Liability",
                format_money(tax_result["annual_tax"])
            )

        with col2:
            st.metric(
                "Monthly PAYE",
                format_money(tax_result["monthly_paye"])
            )

        with st.expander("View Complete Tax Calculation"):
            st.write(
                "**Gross Annual Income:**",
                format_money(tax_result["gross_income"])
            )
            st.write(
                "**Total Deductions/Reliefs:**",
                format_money(tax_result["deductions"])
            )
            st.write(
                "**Taxable Income:**",
                format_money(tax_result["taxable_income"])
            )
            st.write(
                "**Annual Tax Liability:**",
                format_money(tax_result["annual_tax"])
            )
            st.write(
                "**Monthly PAYE:**",
                format_money(tax_result["monthly_paye"])
            )

        if st.button("Save Tax Evaluation", use_container_width=True):
            try:
                save_tax_evaluation(
                    tax_result["employee_id"],
                    tax_result["evaluation_date"],
                    tax_result["gross_income"],
                    tax_result["deductions"],
                    tax_result["taxable_income"],
                    tax_result["annual_tax"],
                    tax_result["monthly_paye"]
                )

                st.success("Tax evaluation saved successfully.")

            except Exception as error:
                st.error(f"Unable to save tax evaluation: {error}")

else:
    st.info(
        "No civil servants have been registered yet. "
        "Register a civil servant before evaluating tax."
    )


st.divider()


