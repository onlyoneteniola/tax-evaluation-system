st.header("👤 Register Civil Servant")

with st.form("registration_form", clear_on_submit=False):

    col1, col2 = st.columns(2)

    with col1:
        employee_id = st.text_input(
            "Employee ID",
            placeholder="e.g. CS003"
        ).strip().upper()

        full_name = st.text_input(
            "Full Name",
            placeholder="Enter the employee's full name"
        ).strip()

        gender = st.selectbox(
            "Gender",
            ["Male", "Female", "Other"]
        )

        department = st.text_input(
            "Department",
            placeholder="e.g. Finance"
        ).strip()

    with col2:
        position = st.text_input(
            "Position",
            placeholder="e.g. Senior Officer"
        ).strip()

        basic_salary = st.number_input(
            "Basic Salary (Monthly, NGN)",
            min_value=0.0,
            value=150000.0,
            step=5000.0
        )

        housing_allowance = st.number_input(
            "Housing Allowance (Monthly, NGN)",
            min_value=0.0,
            value=30000.0,
            step=1000.0
        )

        transport_allowance = st.number_input(
            "Transport Allowance (Monthly, NGN)",
            min_value=0.0,
            value=20000.0,
            step=1000.0
        )

        other_allowance = st.number_input(
            "Other Allowances (Monthly, NGN)",
            min_value=0.0,
            value=10000.0,
            step=1000.0
        )

    register_button = st.form_submit_button(
        "Register Civil Servant",
        use_container_width=True
    )

    if register_button:
        if not employee_id or not full_name:
            st.error("Employee ID and Full Name are required.")

        elif not department or not position:
            st.error("Please enter the Department and Position.")

        else:
            try:
                add_civil_servant(
                    employee_id,
                    full_name,
                    gender,
                    department,
                    position,
                    basic_salary,
                    housing_allowance,
                    transport_allowance,
                    other_allowance
                )

                st.success(
                    f"{full_name} has been registered successfully."
                )

            except sqlite3.IntegrityError:
                st.error(
                    "This Employee ID already exists. "
                    "Please use a different Employee ID."
                )

            except Exception as error:
                st.error(f"Registration failed: {error}")


st.divider()


