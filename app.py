def format_money(amount):
    return f"₦{float(amount or 0):,.2f}"


def create_tax_report_pdf(record):
    (
        record_id,
        employee_id,
        employee_name,
        evaluation_date,
        gross_income,
        deductions,
        taxable_income,
        annual_tax,
        monthly_paye
    ) = record

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=45,
        leftMargin=45,
        topMargin=45,
        bottomMargin=45
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "TaxReportTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        fontSize=16,
        leading=21,
        textColor=colors.HexColor("#17365D"),
        spaceAfter=8
    )

    subtitle_style = ParagraphStyle(
        "TaxReportSubtitle",
        parent=styles["Normal"],
        alignment=TA_CENTER,
        fontSize=12,
        leading=16,
        spaceAfter=20
    )

    section_style = ParagraphStyle(
        "TaxReportSection",
        parent=styles["Heading2"],
        fontSize=11,
        leading=14,
        textColor=colors.HexColor("#17365D"),
        spaceBefore=12,
        spaceAfter=8
    )

    body_style = ParagraphStyle(
        "TaxReportBody",
        parent=styles["Normal"],
        fontSize=9,
        leading=14
    )

    story = []

    story.append(
        Paragraph(
            "COMPUTERIZED TAX EVALUATION SYSTEM",
            title_style
        )
    )

    story.append(
        Paragraph(
            "TAX EVALUATION REPORT",
            subtitle_style
        )
    )

    story.append(
        Paragraph("Employee Information", section_style)
    )

    employee_data = [
        ["Employee ID", str(employee_id)],
        ["Full Name", str(employee_name or "Not available")],
        ["Evaluation Date", str(evaluation_date)]
    ]

    employee_table = Table(
        employee_data,
        colWidths=[160, 300]
    )

    employee_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#E8EEF5")),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#B8C4D1")),
        ("PADDING", (0, 0), (-1, -1), 9),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE")
    ]))

    story.append(employee_table)

    story.append(
        Paragraph("Tax Evaluation Details", section_style)
    )

    tax_data = [
        ["Tax Detail", "Amount (NGN)"],
        ["Gross Annual Income", f"{gross_income:,.2f}"],
        ["Total Deductions/Reliefs", f"{deductions:,.2f}"],
        ["Taxable Income", f"{taxable_income:,.2f}"],
        ["Annual Tax Liability", f"{annual_tax:,.2f}"],
        ["Monthly PAYE", f"{monthly_paye:,.2f}"]
    ]

    tax_table = Table(
        tax_data,
        colWidths=[280, 180]
    )

    tax_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#17365D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTNAME", (0, 1), (0, -1), "Helvetica-Bold"),
        ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#F3F6FA")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#B8C4D1")),
        ("ALIGN", (1, 1), (1, -1), "RIGHT"),
        ("PADDING", (0, 0), (-1, -1), 9),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE")
    ]))

    story.append(tax_table)
    story.append(Spacer(1, 22))

    declaration = (
        "Declaration: This report was generated by the Computerized "
        "Tax Evaluation System using the information recorded for the "
        "selected civil servant. The figures should be verified against "
        "applicable tax rules before official use."
    )

    story.append(Paragraph(declaration, body_style))
    story.append(Spacer(1, 25))

    footer_style = ParagraphStyle(
        "TaxReportFooter",
        parent=styles["Normal"],
        alignment=TA_CENTER,
        fontSize=8,
        textColor=colors.grey
    )

    story.append(
        Paragraph(
            "Computerized Tax Evaluation System",
            footer_style
        )
    )

    document.build(story)
    buffer.seek(0)

    return buffer.getvalue()


