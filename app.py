if tax_records:

    records_df = pd.DataFrame(
        tax_records,
        columns=[
            "Record ID",
            "Employee ID",
            "Employee Name",
            "Evaluation Date",
            "Gross Income",
            "Deductions",
            "Taxable Income",
            "Annual Tax",
            "Monthly PAYE"
        ]
    )

